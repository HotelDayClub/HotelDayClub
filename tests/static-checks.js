const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const http = require('http');
const zlib = require('zlib');
const { spawn } = require('child_process');

const root = path.join(__dirname, '..');
const publicDir = path.join(root, 'public');

function walk(dir, base = '') {
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    const abs = path.join(dir, name);
    const rel = base ? base + '/' + name : name;
    if (fs.statSync(abs).isDirectory()) out.push(...walk(abs, rel));
    else out.push({ rel: rel.split(path.sep).join('/'), size: fs.statSync(abs).size });
  }
  return out;
}

function fetch(port, urlPath, headers) {
  return new Promise((resolve, reject) => {
    const req = http.get({ hostname: '127.0.0.1', port, path: urlPath, headers, timeout: 5000 }, res => {
      const chunks = [];
      res.on('data', c => chunks.push(c));
      res.on('end', () => resolve({ status: res.statusCode, headers: res.headers, body: Buffer.concat(chunks) }));
    });
    req.on('timeout', () => { req.destroy(); reject(new Error('timeout ' + urlPath)); });
    req.on('error', reject);
  });
}

function decoded(res) {
  const enc = String(res.headers['content-encoding'] || '');
  if (enc === 'gzip') return zlib.gunzipSync(res.body);
  if (enc === 'br') return zlib.brotliDecompressSync(res.body);
  if (enc) throw new Error('unexpected encoding ' + enc);
  return res.body;
}

function start(port, dir, dataDir) {
  const hwm = path.join(dir, 'hwm16.js');
  fs.writeFileSync(hwm, `
const zlib = require('zlib');
function wrap(name) {
  const orig = zlib[name];
  Object.defineProperty(zlib, name, {
    configurable: true, enumerable: true, writable: true,
    value: function (opts) {
      return orig.call(zlib, Object.assign({}, opts, { writableHighWaterMark: 16 * 1024 }));
    },
  });
}
wrap('createGzip');
wrap('createBrotliCompress');
`);
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, ['-r', hwm, 'server.js'], {
      cwd: root,
      env: {
        ...process.env,
        PORT: String(port),
        DB_PATH: path.join(dir, 'daypass.db'),
        DATA_DIR: dataDir == null ? '' : dataDir,
        NODE_ENV: 'production',
        ADMIN_PASSWORD: 'static-admin',
        DEMO_HOTEL_PASSWORD: 'static-hotel',
        GA_MEASUREMENT_ID: '',
      },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let log = '';
    const timer = setTimeout(() => reject(new Error('server did not start\n' + log)), 30000);
    child.stdout.on('data', c => {
      log += c;
      if (log.includes('Hotel Day Club demo')) { clearTimeout(timer); resolve(child); }
    });
    child.stderr.on('data', c => { log += c; });
    child.on('exit', code => reject(new Error('server exited ' + code + '\n' + log)));
  });
}

async function checkAll(port, files, headers, label) {
  for (const file of files) {
    const urlPath = '/' + file.rel.split('/').map(encodeURIComponent).join('/');
    const res = await fetch(port, urlPath, headers);
    assert.strictEqual(res.status, 200, label + ' ' + file.rel);
    // /robots.txt is generated by a route. The file in public/ is not what is served.
    if (file.rel === 'robots.txt') continue;
    const body = decoded(res);
    assert.strictEqual(body.length, file.size, label + ' ' + file.rel + ' bytes');
  }
}

async function main() {
  const files = walk(publicDir);
  for (const name of ['styles.css', 'app.css', 'pickers.js']) {
    assert.ok(files.some(f => f.rel === name), 'missing ' + name);
  }
  const browser = { 'Accept-Encoding': 'gzip, deflate, br' };
  const gzip = { 'Accept-Encoding': 'gzip' };
  const identity = { 'Accept-Encoding': 'identity' };

  const withDisk = fs.mkdtempSync(path.join(os.tmpdir(), 'hdc-static-disk-'));
  const disk = await start(3341, withDisk, withDisk);
  try {
    await checkAll(3341, files, browser, 'disk br');
    await checkAll(3341, files, gzip, 'disk gzip');
    await checkAll(3341, files, identity, 'disk identity');
  } finally {
    disk.kill();
  }

  const noDisk = fs.mkdtempSync(path.join(os.tmpdir(), 'hdc-static-nodisk-'));
  const plain = await start(3342, noDisk, null);
  try {
    await checkAll(3342, files, browser, 'nodisk br');
    for (const name of ['styles.css', 'app.css', 'pickers.js']) {
      const res = await fetch(3342, '/' + name, gzip);
      assert.strictEqual(res.status, 200, name);
      assert.strictEqual(decoded(res).length, files.find(f => f.rel === name).size);
    }
  } finally {
    plain.kill();
  }
  console.log('static checks passed', files.length, 'files');
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
